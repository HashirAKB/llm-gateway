/**
 * Reproducible load test against the mock provider.
 *
 *   npm run loadtest            (about 1 minute)
 *   LOADTEST_DURATION=30 npm run loadtest
 *
 * Each scenario starts a fresh gateway in this process (fresh cache, breakers,
 * meters) on a random port, drives it with autocannon, and records every
 * response time so we can report exact p50/p95/p99. Results are written to
 * loadtest/results.md and loadtest/results.json.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { cpus } from "node:os";
import type { AddressInfo } from "node:net";
import autocannon from "autocannon";
import { buildApp } from "../src/app.js";
import { parseConfig } from "../src/config.js";
import { percentile } from "../src/metering.js";
import { MockProvider, seededRandom } from "../src/providers/mock.js";

const DURATION_S = Number(process.env.LOADTEST_DURATION ?? 10);
const CONNECTIONS = Number(process.env.LOADTEST_CONNECTIONS ?? 50);
const UPSTREAM_LATENCY_MS = 50;
/** Distinct prompts the clients cycle through; a small set makes repeats (cache hits) likely. */
const DISTINCT_PROMPTS = 100;
const KEY = "loadtest-key-0001";

interface Scenario {
  name: string;
  description: string;
  cacheEnabled: boolean;
  errorRate: number;
  maxAttempts: number;
}

const scenarios: Scenario[] = [
  { name: "cache off", description: "every request goes upstream", cacheEnabled: false, errorRate: 0, maxAttempts: 3 },
  { name: "cache on", description: `${DISTINCT_PROMPTS} distinct prompts, temperature 0`, cacheEnabled: true, errorRate: 0, maxAttempts: 3 },
  { name: "10% errors, no retries", description: "cache off, maxAttempts 1", cacheEnabled: false, errorRate: 0.1, maxAttempts: 1 },
  { name: "10% errors, retries", description: "cache off, maxAttempts 3, backoff 25-250ms", cacheEnabled: false, errorRate: 0.1, maxAttempts: 3 },
];

interface Row {
  scenario: string;
  description: string;
  requests: number;
  throughputRps: number;
  p50: number;
  p95: number;
  p99: number;
  errorRatePct: number;
}

async function run(scenario: Scenario): Promise<Row> {
  const config = parseConfig({
    keys: [{ key: KEY, name: "loadtest" }],
    routes: { fast: [{ provider: "mock", model: "mock-fast" }] },
    prices: { "mock-fast": { inputPerMTok: 0.1, outputPerMTok: 0.5 } },
    resilience: {
      timeoutMs: 5_000,
      retry: { maxAttempts: scenario.maxAttempts, baseDelayMs: 25, maxDelayMs: 250 },
      // Breaker left at its defaults (5 consecutive failures, 30s cooldown).
    },
    cache: { enabled: scenario.cacheEnabled },
    guardrails: { piiRedaction: true },
  });
  const providers = new Map([
    ["mock", new MockProvider({ latencyMs: UPSTREAM_LATENCY_MS, errorRate: scenario.errorRate, random: seededRandom(7) })],
  ]);
  const app = buildApp({ config, providers, logger: false });
  await app.listen({ port: 0, host: "127.0.0.1" });
  const { port } = app.server.address() as AddressInfo;

  const latencies: number[] = [];
  let sent = 0;
  const result = await autocannon({
    url: `http://127.0.0.1:${port}/v1/messages`,
    method: "POST",
    connections: CONNECTIONS,
    duration: DURATION_S,
    headers: { "content-type": "application/json", "x-api-key": KEY },
    requests: [
      {
        setupRequest: (req) => {
          sent += 1;
          const body = {
            model: "fast",
            max_tokens: 64,
            temperature: 0,
            messages: [{ role: "user", content: `Question number ${sent % DISTINCT_PROMPTS}: what is a gateway?` }],
          };
          return { ...req, body: JSON.stringify(body) };
        },
      },
    ],
    setupClient: (client) => {
      client.on("response", (_status, _bytes, responseTime) => latencies.push(responseTime));
    },
  });
  await app.close();

  latencies.sort((a, b) => a - b);
  const total = result["2xx"] + result.non2xx;
  return {
    scenario: scenario.name,
    description: scenario.description,
    requests: total,
    throughputRps: Math.round(total / result.duration),
    p50: round(percentile(latencies, 50)),
    p95: round(percentile(latencies, 95)),
    p99: round(percentile(latencies, 99)),
    errorRatePct: total === 0 ? 0 : round((result.non2xx / total) * 100, 2),
  };
}

function round(n: number, digits = 1): number {
  return Number(n.toFixed(digits));
}

function toMarkdown(rows: Row[]): string {
  const cpu = cpus()[0]?.model ?? "unknown CPU";
  const lines = [
    "# Load test results",
    "",
    `Generated by \`npm run loadtest\` on ${new Date().toISOString().slice(0, 10)}.`,
    `Machine: ${cpu}, ${cpus().length} cores, Node ${process.version}.`,
    `Setup: ${CONNECTIONS} concurrent connections, ${DURATION_S}s per scenario, mock upstream latency ${UPSTREAM_LATENCY_MS}ms, logging off.`,
    "Latencies are client-observed, in milliseconds. Error rate is the share of non-2xx responses.",
    "",
    "| Scenario | Setup | Requests | Throughput (req/s) | p50 | p95 | p99 | Error rate |",
    "|---|---|---:|---:|---:|---:|---:|---:|",
    ...rows.map(
      (r) =>
        `| ${r.scenario} | ${r.description} | ${r.requests} | ${r.throughputRps} | ${r.p50} | ${r.p95} | ${r.p99} | ${r.errorRatePct}% |`,
    ),
    "",
  ];
  return lines.join("\n");
}

const rows: Row[] = [];
for (const scenario of scenarios) {
  process.stdout.write(`Running "${scenario.name}" for ${DURATION_S}s... `);
  const row = await run(scenario);
  rows.push(row);
  console.log(`${row.throughputRps} req/s, p95 ${row.p95}ms, errors ${row.errorRatePct}%`);
}

mkdirSync("loadtest", { recursive: true });
writeFileSync("loadtest/results.json", JSON.stringify(rows, null, 2) + "\n");
writeFileSync("loadtest/results.md", toMarkdown(rows));
console.log("\n" + toMarkdown(rows));
